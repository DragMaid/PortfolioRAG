/** The letter shown for a service with no mark above. */
const contactLetters: Partial<Record<ContactIcon, string>> = {
  Mastodon: "M",
  Threads: "@",
  Behance: "B",
  DevTo: "D",
};

/** Resolves a `ContactLink.icon` discriminator to its mark. */
export function ContactGlyph({ name, ...props }: IconProps & { name: ContactIcon }) {
  const Glyph = contactIcons[name];
  if (Glyph) return <Glyph {...props} />;

  return <LetterMark letter={contactLetters[name] ?? name.charAt(0)} {...props} />;
}
